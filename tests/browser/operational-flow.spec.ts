import { test, expect } from './fixtures'

test('incident and recorded-operation attention follow request health without revealing the diagnosis', async ({ page }) => {
  await page.goto('/')
  if (await page.getByTestId('onboarding-skip').isVisible()) await page.getByTestId('onboarding-skip').click()
  await page.getByTestId('play-adventure').click()
  await page.getByTestId('adventure-start-investigate-incident').click()
  await page.getByTestId('mission-watch-flow').click()
  await expect(page.getByTestId('watch-flow')).toContainText('Needs attention')
  await expect(page.getByTestId('watch-flow')).not.toContainText('DB_POOL_MAX')
  await page.getByTestId('flow-exit').click()
  await page.getByTestId('guide-me-world').click()
  await expect(page.getByTestId('station-attention')).toHaveAttribute('data-status', 'failed')
  await page.getByTestId('guide-inspect').click()
  for (const action of ['inspect-alert', 'inspect-metrics', 'inspect-logs', 'diagnose-pool', 'repair-pool']) await page.getByTestId(`adventure-action-${action}`).click()
  await expect(page.locator('.mission-automation')).toBeHidden()
  await page.getByTestId('adventure-action-inspect-metrics').click()
  await page.getByTestId('adventure-action-verify-incident').click()
  await expect(page.getByTestId('mission-status')).toHaveText('Adventure complete')
  const before = await page.evaluate(() => localStorage.getItem('awushi-adventures-v2'))
  await page.getByTestId('close-mission').click()
  await page.getByTestId('watch-flow-start').click()
  await expect(page.getByTestId('flow-title')).toHaveText('Adventure complete')
  await expect(page.getByTestId('watch-flow')).toContainText('Healthy')
  await page.getByTestId('flow-replay').click()
  while (await page.getByTestId('flow-previous').isEnabled()) await page.getByTestId('flow-previous').click()
  await expect(page.getByTestId('flow-title')).toHaveText('Recorded infrastructure state')
  await expect(page.getByTestId('watch-flow')).toContainText('Needs attention')
  await expect(page.locator('canvas')).toHaveAttribute('data-camera-station', 'alerts')
  await page.getByTestId('flow-live').click()
  await expect(page.getByTestId('flow-title')).toHaveText('Adventure complete')
  expect(await page.evaluate(() => localStorage.getItem('awushi-adventures-v2'))).toBe(before)
})
