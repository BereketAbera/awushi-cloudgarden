test('keyboard users can open event history and receive pipeline status inside the modal', async ({ page }) => {
  await page.goto('/')
  await page.getByTestId('play-adventure').click()
  await page.getByTestId('open-simulation').click()
  const close = page.getByTestId('close-dialog')
  const history = page.locator('.event-history summary')
  await expect(close).toBeFocused()
  await page.keyboard.press('Shift+Tab')
  await expect(history).toBeFocused()
  await page.keyboard.press('Enter')
  await expect(page.locator('.event-history')).toHaveAttribute('open', '')
  await page.keyboard.press('Tab')
  await expect(close).toBeFocused()
  const status = page.getByRole('dialog').getByRole('status')
  await expect(status).toHaveAttribute('aria-live', 'polite')
  await expect(status).toHaveAttribute('aria-atomic', 'true')
  await page.getByTestId('simulation-start').click()
  await expect(status).toContainText('In progress')
  await page.getByTestId('simulation-cancel').click()
  await expect(status).toContainText('Run cancelled')
})
