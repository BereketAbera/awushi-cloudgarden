import { test, expect } from './fixtures'

test('complete deployment waits for a person, reconciles the chosen environment and exposes telemetry', async ({ page }, info) => {
  test.skip(info.project.name !== 'desktop', 'Full timed journey runs once; mobile uses the same domain reducer.')
  test.setTimeout(100_000)
  const errors: string[] = []
  page.on('pageerror', error => errors.push(error.message))
  await page.goto('/')
  await page.getByTestId('play-adventure').click()
  await page.getByTestId('open-simulation').click()
  await expect(page.getByTestId('simulation-panel')).toBeVisible()
  await page.getByTestId('simulation-start').click()
  await expect(page.getByTestId('pipeline-status')).toHaveText('Your approval is needed', { timeout: 20_000 })
  await expect(page.getByTestId('approval-digest')).toContainText('sha256:')
  await expect(page.getByTestId('deployment-revision')).toHaveText('0')
  await page.waitForTimeout(1200)
  await expect(page.getByTestId('pipeline-status')).toHaveText('Your approval is needed')
  await expect(page.getByTestId('close-dialog')).toBeInViewport({ ratio: 1 })
  await page.screenshot({ path: 'assets/previews/phase2-approval-desktop.png' })
  await page.getByTestId('simulation-approve').click()
  await expect(page.getByTestId('pipeline-status')).toHaveText('Deployment healthy', { timeout: 35_000 })
  await expect(page.getByTestId('deployment-revision')).toHaveText('1')
  await expect(page.getByTestId('gitops-health')).toHaveText('Synced / Healthy')
  await expect(page.getByTestId('traffic-status')).toHaveText('Ready / Ready')
  await expect(page.getByTestId('telemetry-status')).toContainText('Visible')
  await page.getByText(/Event history ·/).click()
  await expect(page.getByTestId('simulation-history')).toContainText('approved')
  await expect(page.getByTestId('simulation-history')).toContainText('succeeded')
  await page.getByRole('combobox', { name: 'Pipeline environment', exact: true }).selectOption('production')
  await expect(page.getByTestId('deployment-revision')).toHaveText('0')
  await page.getByRole('combobox', { name: 'Pipeline environment', exact: true }).selectOption('development')
  await expect(page.getByTestId('deployment-revision')).toHaveText('1')
  await page.screenshot({ path: 'assets/previews/phase2-deployment-desktop.png' })
  await page.getByTestId('simulation-reset').click()
  await expect(page.getByTestId('pipeline-status')).toHaveText('Ready when you are')
  await expect(page.getByTestId('deployment-revision')).toHaveText('0')
  expect(errors).toEqual([])
})

