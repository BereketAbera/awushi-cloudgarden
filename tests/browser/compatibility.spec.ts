import { test, expect } from './fixtures'

test('portfolio, shared architecture lenses and immersive controls work across browsers', async ({ page }, info) => {
  await page.goto('/')
  await expect(page.locator('canvas')).toHaveAttribute('data-camera-mode', 'overview')
  await page.screenshot({ path: `assets/previews/phase3-landing-${info.project.name}.png` })
  await page.getByTestId('open-showcase').click()
  await expect(page.getByTestId('engineering-showcase')).toContainText('43')
  await page.getByTestId('showcase-layer-authoring').click()
  await expect(page.locator('.showcase-detail')).toContainText('five reusable clips')
  await page.getByTestId('close-dialog').click()
  await page.getByTestId('view-architecture').click()
  for (const flow of ['delivery', 'security', 'observability', 'data']) {
    await page.getByTestId(`architecture-flow-${flow}`).click()
    await expect(page.getByTestId(`architecture-flow-${flow}`)).toHaveAttribute('aria-pressed', 'true')
  }
  await page.getByRole('combobox', { name: 'Architecture environment', exact: true }).selectOption('production')
  await expect(page.getByTestId('architecture-boundary')).toContainText('awushi-prod')
  await page.getByTestId('close-dialog').click()
  await page.getByTestId('free-explore').click()
  const canvas = page.locator('canvas')
  await expect(canvas).toHaveAttribute('data-camera-projection', 'perspective')
  await page.getByTestId('camera-first-person').click()
  await expect(canvas).toHaveAttribute('data-character-visible', 'false')
  const before = await canvas.getAttribute('data-view-yaw'), bounds = (await canvas.boundingBox())!
  await page.mouse.move(bounds.x + bounds.width * .5, bounds.y + bounds.height * .45)
  await page.mouse.down(); await page.mouse.move(bounds.x + bounds.width * .6, bounds.y + bounds.height * .48, { steps: 6 }); await page.mouse.up()
  await expect(canvas).not.toHaveAttribute('data-view-yaw', before!)
  await page.getByRole('button', { name: 'Open settings', exact: true }).click()
  await page.getByTestId('reduced-motion').check()
  await page.getByTestId('close-dialog').click()
  await page.getByTestId('camera-third-person').click()
  await expect(canvas).toHaveAttribute('data-character-visible', 'true')
  expect(await page.evaluate(() => document.documentElement.scrollWidth <= window.innerWidth + 1)).toBeTruthy()
  await page.screenshot({ path: `assets/previews/phase3-compatible-${info.project.name}.png` })
})

test('original local audio is opt-in, respects mute and releases finished voices', async ({ page }) => {
  await page.goto('/')
  await page.getByRole('button', { name: 'Open settings', exact: true }).click()
  await expect(page.getByTestId('sound-enabled')).not.toBeChecked()
  await expect(page.getByTestId('audio-status')).toHaveText('muted')
  await expect(page.getByTestId('audio-status')).toHaveAttribute('data-cues-played', '0')
  await page.getByTestId('sound-enabled').check()
  await expect(page.getByTestId('audio-status')).toHaveText('ready')
  await expect.poll(async () => Number(await page.getByTestId('audio-status').getAttribute('data-cues-played'))).toBeGreaterThan(0)
  await expect(page.getByTestId('audio-status')).toHaveAttribute('data-active-voices', '0')
  await page.getByRole('slider', { name: 'Sound volume' }).fill('0.2')
  await page.getByTestId('sound-enabled').uncheck()
  await expect(page.getByTestId('audio-status')).toHaveText('muted')
  await page.reload()
  await page.getByRole('button', { name: 'Open settings', exact: true }).click()
  await expect(page.getByTestId('sound-enabled')).not.toBeChecked()
  await expect(page.getByRole('slider', { name: 'Sound volume' })).toHaveValue('0.2')
})
