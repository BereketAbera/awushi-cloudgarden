import { test, expect } from './fixtures'

test('incident investigation stays readable from station focus through evidence and recovery', async ({ page }, info) => {
  await page.goto('/')
  if (await page.getByTestId('onboarding-skip').isVisible()) await page.getByTestId('onboarding-skip').click()
  await page.getByTestId('play-adventure').click()
  await page.getByTestId('adventure-start-investigate-incident').click()
  await page.screenshot({ path: `assets/previews/phase4-incident-brief-${info.project.name}.png` })
  await page.getByTestId('guide-me').click()
  await expect(page.locator('canvas')).toHaveAttribute('data-camera-station', 'alerts')
  await expect(page.locator('canvas')).toHaveAttribute('data-camera-settled', 'true')
  await page.screenshot({ path: `assets/previews/phase4-incident-focus-${info.project.name}.png` })
  await page.getByTestId('guide-inspect').click()
  for (const action of ['inspect-alert', 'inspect-metrics', 'inspect-logs']) await page.getByTestId(`adventure-action-${action}`).click()
  await expect(page.getByTestId('latest-evidence')).toContainText('DB_POOL_MAX')
  await page.getByTestId('latest-evidence').scrollIntoViewIfNeeded()
  await page.screenshot({ path: `assets/previews/phase4-incident-evidence-${info.project.name}.png` })
  await page.getByTestId('adventure-action-diagnose-ingress').click()
  await expect(page.getByTestId('mission-feedback')).toContainText('conflicts with the evidence')
  await page.getByTestId('mission-feedback').scrollIntoViewIfNeeded()
  await page.screenshot({ path: `assets/previews/phase4-incident-feedback-${info.project.name}.png` })
  await page.getByTestId('adventure-action-diagnose-pool').click()
  await page.getByTestId('adventure-action-repair-pool').click()
  await expect(page.locator('.mission-automation')).toBeHidden()
  await page.getByTestId('adventure-action-inspect-metrics').click()
  await page.getByTestId('adventure-action-verify-incident').click()
  await expect(page.getByTestId('mission-status')).toHaveText('Adventure complete')
  await page.getByTestId('learning-summary').scrollIntoViewIfNeeded()
  await page.screenshot({ path: `assets/previews/phase4-incident-complete-${info.project.name}.png` })
  expect(await page.evaluate(() => document.documentElement.scrollWidth > innerWidth + 1)).toBe(false)
})
