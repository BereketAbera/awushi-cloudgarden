test('reload resumes a saved reconciliation, and replay controls keep the completed record immutable', async ({ page }, info) => {
  test.setTimeout(90_000)
  await start(page, 'fix-drift', 'manual')
  await act(page, 'inspect-git'); await act(page, 'inspect-live'); await act(page, 'sync-git')
  await expect(automation(page)).toBeVisible()
  await page.getByTestId('adventure-pause').click()
  await expect(page.getByTestId('mission-status')).toContainText('Paused')
  await expect(page.getByTestId('adventure-action-verify-drift')).toBeDisabled()
  const beforeReload = (await notebook(page)).active!
  expect(beforeReload.commands.at(-1)?.command).toEqual({type:'action',actionId:'sync-git'})
  expect(beforeReload.elapsedMs - beforeReload.commands.at(-1)!.at).toBeLessThan(2400)
  await page.reload()
  await expect(page.getByTestId('resume-adventure-welcome')).toBeVisible()
  const restored = (await notebook(page)).active!
  expect(restored.commands).toEqual(beforeReload.commands)
  expect(restored.elapsedMs).toBe(beforeReload.elapsedMs)
  await page.getByTestId('resume-adventure-welcome').click()
  await settle(page, 10_000)
  await act(page, 'verify-drift')
  await complete(page, 'fix-drift', `resumed-${info.project.name}`)
  const completed = JSON.stringify((await notebook(page)).completed)
  await page.getByTestId('replay-start').click()
  await expect(page.getByTestId('replay-controls')).toBeVisible()
  await page.getByTestId('replay-toggle').click()
  await expect(page.getByTestId('replay-toggle')).toHaveText('Play')
  const progress = page.getByRole('progressbar', {name:'Replay progress',exact:true})
  const pausedAt = await progress.getAttribute('value')
  await page.waitForTimeout(350) // Assert paused time, rather than advancing the application clock.
  expect(await progress.getAttribute('value')).toBe(pausedAt)
  await page.getByTestId('replay-speed').selectOption('4')
  await page.getByTestId('replay-restart').click()
  await expect(page.getByTestId('replay-speed')).toHaveValue('4')
  await expect(page.getByTestId('mission-status')).toHaveText('Adventure complete', {timeout:15_000})
  expect(JSON.stringify((await notebook(page)).completed)).toBe(completed)
  await page.getByTestId('replay-stop').click()
  await expect(page.getByTestId('replay-controls')).toHaveCount(0)
  await expect(page.getByTestId('mission-status')).toHaveText('Adventure complete')
  expect(JSON.stringify((await notebook(page)).completed)).toBe(completed)
})
