import { mkdirSync } from 'node:fs'
import { test, expect, type Page } from './fixtures'
import type { AdventureId, AdventureVariant } from '../../src/adventures/domain'
import type { AdventureSave } from '../../src/adventures/persistence'

const act = (page: Page, id: string) => page.getByTestId(`adventure-action-${id}`).click()
const feedback = (page: Page) => page.getByTestId('mission-feedback')
const automation = (page: Page) => page.locator('.mission-automation')
async function start(page: Page, id: AdventureId, variant?: AdventureVariant) {
  await page.goto('/')
  await page.getByTestId('play-adventure').click()
  await expect(page.getByTestId('adventure-select')).toBeVisible()
  if (variant) await page.getByTestId(`adventure-variant-${id}`).selectOption(variant)
  await page.getByTestId(`adventure-start-${id}`).click()
  await expect(page.getByTestId('mission-panel')).toBeVisible()
  await expect(page.getByTestId('mission-status')).toHaveText('Adventure in progress')
}
async function settle(page: Page, timeout = 45_000) {
  await expect(automation(page)).toBeVisible()
  await expect(automation(page)).toBeHidden({ timeout })
}
async function latestFields(page: Page, title: string, expected: Record<string, string | RegExp> = {}) {
  const evidence = page.getByTestId('latest-evidence')
  await expect(evidence.locator('summary')).toContainText(title)
  for (const [label, value] of Object.entries(expected)) {
    await expect(evidence.locator('dl > div').filter({ has: page.locator('dt', { hasText: new RegExp(`^${label.replace(/[.*+?^${}()|[\]\\]/g, '\\$&')}$`) }) }).locator('dd')).toHaveText(value)
  }
  return evidence.locator('dl > div').evaluateAll(nodes => Object.fromEntries(nodes.map(node => [node.querySelector('dt')?.textContent ?? '', node.querySelector('dd')?.textContent ?? ''])))
}
async function notebook(page: Page): Promise<AdventureSave> {
  return page.evaluate(() => JSON.parse(localStorage.getItem('awushi-adventures-v2') ?? 'null'))
}
async function complete(page: Page, id: AdventureId, project: string) {
  await expect(page.getByTestId('mission-status')).toHaveText('Adventure complete')
  await expect(page.getByTestId('learning-summary')).toBeVisible()
  await expect.poll(async () => (await notebook(page)).completed.some(record => record.adventureId === id)).toBe(true)
  await page.getByTestId('learning-summary').scrollIntoViewIfNeeded()
  expect(await page.evaluate(() => document.documentElement.scrollWidth > window.innerWidth + 1)).toBe(false)
  mkdirSync('assets/previews', { recursive: true })
  await page.screenshot({ path: `assets/previews/phase3-${id}-${project}.png` })
}

test('Ship a New Release: failed checks block approval until inspected, repaired and verified', async ({ page }, info) => {
  test.setTimeout(120_000)
  await start(page, 'ship-release')
  await act(page, 'push')
  await expect(page.getByTestId('adventure-action-repair-tests')).toBeVisible({ timeout: 15_000 })
  await act(page, 'approve-release')
  await expect(feedback(page)).toContainText('Approval is blocked')
  await expect(page.getByTestId('mission-objective')).toHaveText('Investigate and verify CI')
  await act(page, 'retry-ci')
  await expect(feedback(page)).toContainText('unchanged')
  await act(page, 'inspect-ci')
  expect((await latestFields(page, 'CI results', { Tests: 'failed' })).Tests).toBe('failed')
  await act(page, 'repair-tests')
  await settle(page)
  await act(page, 'inspect-ci')
  expect((await latestFields(page, 'CI results', { Pipeline: 'passed' })).Pipeline).toBe('passed')
  await act(page, 'inspect-image')
  expect((await latestFields(page, 'Published immutable image'))['Reviewed digest']).toMatch(/^sha256:[a-f0-9]{64}$/)
  await act(page, 'approve-release')
  await settle(page)
  for (const action of ['inspect-gitops', 'verify-health', 'verify-routing', 'inspect-telemetry']) await act(page, action)
  await complete(page, 'ship-release', info.project.name)
  const saved = (await notebook(page)).completed.find(record => record.adventureId === 'ship-release')!
  expect(saved.result!.mistakes).toBeGreaterThanOrEqual(2)
})

test('Recover a Failed Pod: four causes distinguish controller recovery from configuration repair', async ({ page }, info) => {
  test.setTimeout(120_000)
  const variants = [
    { id: 'readiness', fix: 'repair-readiness', evidence: 'Running / Ready=False' },
    { id: 'image', fix: 'repair-image', evidence: 'ImagePullBackOff' },
    { id: 'resources', fix: 'repair-resources', evidence: 'Pending / Unschedulable' },
    { id: 'transient', fix: 'wait-controller', evidence: 'Terminated / waiting for restart' },
  ] as const
  for (const variant of variants) {
    await start(page, 'recover-pod', variant.id)
    await act(page, 'inspect-pod')
    expect((await latestFields(page, 'Pod status, events and metrics', { 'Current status': variant.evidence }))['Current status']).toBe(variant.evidence)
    await act(page, 'restart-pod')
    await expect(feedback(page)).toContainText(variant.id === 'transient' ? 'kubelet already' : 'configuration unchanged')
    await act(page, variant.fix)
    if (variant.id === 'transient') await settle(page, 15_000)
    await act(page, 'verify-pod')
    await complete(page, 'recover-pod', `${variant.id}-${info.project.name}`)
  }
})

test('Fix Configuration Drift: waiting without self-heal fails, manual and automatic modes converge', async ({ page }, info) => {
  test.setTimeout(90_000)
  await start(page, 'fix-drift', 'manual')
  await act(page, 'inspect-git')
  expect((await latestFields(page, 'Desired Git configuration'))['Reviewed replicas']).toBe('2')
  await act(page, 'inspect-live')
  expect((await latestFields(page, 'Live configuration and sync policy'))['Automated sync + selfHeal']).toBe('Disabled')
  await act(page, 'wait-self-heal')
  await expect(feedback(page)).toContainText('Self-heal is disabled')
  await expect(automation(page)).toHaveCount(0)
  await act(page, 'inspect-live')
  expect((await latestFields(page, 'Live configuration and sync policy'))['Argo status']).toBe('OutOfSync')
  await act(page, 'sync-git')
  await settle(page, 10_000)
  await act(page, 'verify-drift')
  await complete(page, 'fix-drift', `manual-${info.project.name}`)
  await start(page, 'fix-drift', 'self-heal')
  await act(page, 'inspect-git'); await act(page, 'inspect-live')
  expect((await latestFields(page, 'Live configuration and sync policy'))['Automated sync + selfHeal']).toBe('Enabled')
  await act(page, 'wait-self-heal')
  await settle(page, 15_000)
  await act(page, 'verify-drift')
  await complete(page, 'fix-drift', `self-heal-${info.project.name}`)
})

test('Promote to Production: explicit review promotes the exact development digest independently', async ({ page }, info) => {
  test.setTimeout(120_000)
  await start(page, 'promote-production')
  await act(page, 'push')
  await act(page, 'propose-production')
  await expect(feedback(page)).toContainText('Verify the deployed development digest')
  await settle(page)
  await act(page, 'inspect-ci'); await act(page, 'inspect-image')
  await act(page, 'approve-release'); await settle(page)
  await act(page, 'verify-development')
  const development = await latestFields(page, 'Verified development release')
  expect(development['Verified digest']).toMatch(/^sha256:[a-f0-9]{64}$/)
  await act(page, 'propose-production')
  await settle(page)
  await act(page, 'approve-production')
  await expect(feedback(page)).toContainText('Review the production diff')
  await act(page, 'review-production')
  const proposal = await latestFields(page, 'Production promotion diff')
  expect(proposal['Production proposed digest']).toBe(development['Verified digest'])
  expect(proposal['Development verified digest']).toBe(development['Verified digest'])
  expect(proposal['Target namespace']).toBe('awushi-prod')
  await act(page, 'approve-production'); await settle(page)
  await act(page, 'verify-production')
  await complete(page, 'promote-production', info.project.name)
  const production = await page.locator('.evidence-history .evidence-card').filter({ hasText: 'Independent production release' }).locator('dl > div').evaluateAll(nodes => Object.fromEntries(nodes.map(node => [node.querySelector('dt')?.textContent ?? '', node.querySelector('dd')?.textContent ?? ''])))
  expect(production['Active digest']).toBe(development['Verified digest'])
  expect(production['Development unchanged']).toBe('Digest and revision retained')
})

